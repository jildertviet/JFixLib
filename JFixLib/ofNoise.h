inline float grad1(int hash, float x) {
  int h = hash & 15;
  float grad = 1.0f + (h & 7);
  if (h & 8) grad = -grad;
  return (grad * x);
}

inline float grad2(int hash, float x, float y) {
  int h = hash & 7;
  float u = h < 4 ? x : y;
  float v = h < 4 ? y : x;
  return ((h & 1) ? -u : u) + ((h & 2) ? -2.0f * v : 2.0f * v);
}

inline float grad3(int hash, float x, float y, float z) {
  int h = hash & 15;
  float u = h < 8 ? x : y;
  float v = h < 4 ? y : h == 12 || h == 14 ? x : z;
  return ((h & 1) ? -u : u) + ((h & 2) ? -v : v);
}

inline float _slang_library_noise3(float x, float y, float z) {
  constexpr float F3 = 0.333333333f;
  constexpr float G3 = 0.166666667f;

  float s = (x + y + z) * F3;
  int i = OFNOISE_FASTFLOOR(x + s);
  int j = OFNOISE_FASTFLOOR(y + s);
  int k = OFNOISE_FASTFLOOR(z + s);

  float t = (float)(i + j + k) * G3;
  float x0 = x - (i - t);
  float y0 = y - (j - t);
  float z0 = z - (k - t);

  int i1, j1, k1;
  int i2, j2, k2;

  if (x0 >= y0) {
    if (y0 >= z0) { i1 = 1; j1 = 0; k1 = 0; i2 = 1; j2 = 1; k2 = 0; }
    else if (x0 >= z0) { i1 = 1; j1 = 0; k1 = 0; i2 = 1; j2 = 0; k2 = 1; }
    else { i1 = 0; j1 = 0; k1 = 1; i2 = 1; j2 = 0; k2 = 1; }
  } else {
    if (y0 < z0) { i1 = 0; j1 = 0; k1 = 1; i2 = 0; j2 = 1; k2 = 1; }
    else if (x0 < z0) { i1 = 0; j1 = 1; k1 = 0; i2 = 0; j2 = 1; k2 = 1; }
    else { i1 = 0; j1 = 1; k1 = 0; i2 = 1; j2 = 1; k2 = 0; }
  }

  float x1 = x0 - i1 + G3;
  float y1 = y0 - j1 + G3;
  float z1 = z0 - k1 + G3;
  float x2 = x0 - i2 + 2.0f * G3;
  float y2 = y0 - j2 + 2.0f * G3;
  float z2 = z0 - k2 + 2.0f * G3;
  float x3 = x0 - 1.0f + 3.0f * G3;
  float y3 = y0 - 1.0f + 3.0f * G3;
  float z3 = z0 - 1.0f + 3.0f * G3;

  int ii = i % 256;
  int jj = j % 256;
  int kk = k % 256;

  auto get_n = [&](float x, float y, float z, int i_off, int j_off, int k_off) {
    float t = 0.6f - x * x - y * y - z * z;
    if (t < 0.0f) return 0.0f;
    t *= t;
    return t * t * grad3(perm[ii + i_off + perm[jj + j_off + perm[kk + k_off]]], x, y, z);
  };

  float n0 = get_n(x0, y0, z0, 0, 0, 0);
  float n1 = get_n(x1, y1, z1, i1, j1, k1);
  float n2 = get_n(x2, y2, z2, i2, j2, k2);
  float n3 = get_n(x3, y3, z3, 1, 1, 1);

  return 32.0f * (n0 + n1 + n2 + n3);
}

inline float ofNoise(float x, float y, float z) {
  return _slang_library_noise3(x, y, z);
}

